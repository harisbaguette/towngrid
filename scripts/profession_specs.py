def view(neck,arms,legs,hem=None):
    left=min(a[0][0] for a in arms)+2;right=max(a[0][0] for a in arms)-2
    hips=[leg[0] for leg in legs];bottom=hem or max(p[1] for p in hips)+4
    body=[[left,neck],[right,neck],[right-1,bottom-15],[max(p[0] for p in hips)+5,bottom],
          [min(p[0] for p in hips)-5,bottom],[left,bottom-15]]
    return [neck,arms,legs,body]

