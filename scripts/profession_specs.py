def write_specs():
    roster_specs.ROOT=ROOT
    for identity,name,race,gender,profession,tool,description in CAST:
        if identity not in DATA:continue
        roster_specs.RACES[identity]=race
        spec=roster_specs.build(identity,DATA[identity])
        spec.update({'name':name,'gender':gender,'profession':profession,'workStyle':profession,'partRadius':24,
                     'toolFile':f'professions-v5/tools/{tool}.png','toolRoot':'art-source/pixel-characters',
                     'weaponFile':'professions-v5/tools/sword.png' if profession=='guard' else None,
                     'weaponStyle':'sword' if profession=='guard' else 'unarmed'})
        (ROOT/identity/'rig.json').write_text(json.dumps(spec,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')

if __name__=='__main__':write_specs()
