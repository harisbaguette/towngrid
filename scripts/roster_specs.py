    race=RACES[identity];height=HEIGHTS[race];kind='spirit' if race=='spirit' else 'centaur' if race=='centaur' else 'biped'
    views=[]
    for name,entry in zip(['SW','NW'],data):
        neck,arms,legs,body=entry
        core=[[0,0],[127,0],[127,neck],[body[1][0],neck]]+body[1:]+[body[0],[0,neck]]
        views.append({'image':name+'.png','core':core,'arms':arms,'legs':legs})
    pelvis=np.mean([np.mean([l[2][1]-l[0][1] for l in v['legs']]) for v in views])/math.sqrt(2/3) if kind!='spirit' else 30
    width=np.mean([abs(v['legs'][1][0][0]-v['legs'][0][0][0]) for v in views])/math.sqrt(2) if kind!='spirit' else 7
    stride=.46*(pelvis/38)*(height/1.05)
    reach=stride*128/height*.55/2
    distances=[math.hypot(pelvis+2/math.sqrt(2/3),width*.32)]
    for i in range(12):
        phase=i/12;bob=-round(1.8*math.sin(phase*math.tau)**2)
        for side in [0,.5]:
            travel,lift,_=foot_phase(phase+side,{'stance':.55,'footLift':3})
